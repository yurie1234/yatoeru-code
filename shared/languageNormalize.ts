const CANONICAL_SET: ReadonlySet<string> = new Set<string>(CANONICAL_LANGUAGES);

/** 全角ハイフン類・波ダッシュを長音記号に寄せる（「ミャンマ－語」対策） */
function unifyDashes(v: string): string {
  return v.replace(/[－‐‑‒–—―ｰ~〜]/g, "ー");
}

/**
 * トークン1件を正式名称に寄せる。言語名として読めなければ null。
 *
 * 「〜語」で終わることを言語名の条件にしている。これで
 * 「シンハラ語は現在未対応）」のような注記が言語として混入しない。
 */
export function normalizeLanguageName(value: string): string | null {
  const v = unifyDashes(String(value ?? ""))
    .replace(/[()（）「」『』\[\]【】]/g, "") // 括弧の残骸を落とす
    .replace(/[0-9０-９]+$/, "") // 「中国語0」のような末尾の数字
    .replace(/^[\s・、,，/／]+|[\s・、,，/／]+$/g, "")
    .trim();
  if (!v) return null;

  if (CANONICAL_SET.has(v)) return v;
  if (LANGUAGE_ALIASES[v]) return LANGUAGE_ALIASES[v];

  // 「語」を省いた語幹だけの記載を拾う。「中国（北京・広東）語」のように
  // 最後の1語にしか「語」が付いていない書き方が登録簿にあり、
  // 括弧で分解すると「北京」「広東」が語幹だけで残る。
  // ただし救えるのは正式名称・別名に載っているものだけにする——
  // 「事業者申告により確認」に「語」を足して言語に化けさせない
  if (!v.endsWith("語")) {
    const stem = `${v}語`;
    if (CANONICAL_SET.has(stem)) return stem;
    if (LANGUAGE_ALIASES[stem]) return LANGUAGE_ALIASES[stem];
    return null;
  }

  // 「語」で終わる1〜11文字なら、地図に無くても言語名として採用する。
  // 知らない言語を黙って消さないための逃げ道。
  // ただし途中に「語」を含むもの（区切り漏れの連結）は弾く
  const stem = v.slice(0, -1);
  if (stem.includes("語")) return null;
  if (/^[ぁ-んァ-ヴーA-Za-z一-鿿]{1,11}$/.test(stem)) return v;

  return null;
}

/**
 * 原文の区切り。括弧も区切りとして扱い、併記の両方を拾う。
 *
 * 末尾の `(?<=語)` は、登録簿に区切り記号を打ち忘れた記載
 * （「ベトナム語中国語」「ミャンマー語シンハラ語」など13機関）を救うためのもの。
 * 「語」の直後で必ず切ることで、連結された記載も1言語ずつ拾える。
 *
 * 順番が重要: 区切り文字のクラスを先に置く。ゼロ幅の後読みを先にすると、
 * 「タガログ語。シンハラ語」の「。」が消費されず次のトークンに残ってしまう。
 */
const SEPARATORS = /[・･、。，,.．\/／|｜＆&+＋'"’”;；:：\n\r\t()（）「」『』\[\]【】\s]+|および|及び|ならびに|並びに|その他|(?<=語)/g;

/**
 * 「対応していない」と明記している言い回し。
 *
 * 登録簿の原文には
 *   「…クメール語（2026年7月16日 事業者申告により確認。中国語・ネパール語・
 *     シンハラ語は現在未対応）」
 * のように、**対応できない言語を名指しする**記載がある。
 * 素朴に言語名を拾うと、機関が自ら否定した言語を対応言語として載せてしまい、
 * その言語が必要な企業に誤って紹介することになる。
 * 否定表現を含む節はまるごと捨てる。
 */
const NEGATION = /未対応|非対応|対応不可|対応外|対応しておりません|対応していません|できません|不可能/;

/** 節の区切り（。（ など）。否定を含む節を落とすために使う */
const CLAUSE_SPLIT = /[。．｡\n（(]/;

function stripNegatedClauses(raw: string): { kept: string; negated: string[] } {
  const clauses = raw.split(CLAUSE_SPLIT);
  if (clauses.length === 1) return { kept: raw, negated: [] };
  const kept: string[] = [];
  const negated: string[] = [];
  for (const c of clauses) {
    if (NEGATION.test(c)) negated.push(c.trim());
    else kept.push(c);
  }
  // 節の区切りは失われるが、後段で同じ区切り集合で分解するため結果は変わらない
  return { kept: kept.join("・"), negated };
}

export interface NormalizedLanguages {
  /** 正式名称に寄せ、重複を除いた対応言語 */
  languages: string[];
  /** 言語名として読めなかったトークン（黙って消さず、確認できる形で返す） */
  unrecognized: string[];
  /** 「未対応」と明記されていたため除外した記載 */
  negated: string[];
}

/**
 * 登録簿の原文（languagesRaw）から対応言語の配列を作る。
 *
 * 表示順は原文の記載順を保つ。原文が「ベトナム語・英語」なら
 * ["ベトナム語","英語"] になり、機関が自分で挙げた優先順が消えない。
 */
export function normalizeLanguages(raw: string | null | undefined): NormalizedLanguages {
  const languages: string[] = [];
  const unrecognized: string[] = [];
  const { kept, negated } = stripNegatedClauses(String(raw ?? ""));
  for (const token of kept.split(SEPARATORS)) {
    const t = token.trim();
    if (!t) continue;
    const n = normalizeLanguageName(t);
    if (n) {
      if (!languages.includes(n)) languages.push(n);
      continue;
    }
    // 記号・数字だけの断片は「読めなかった」に数えない（確認すべき件数を埋もれさせない）
    if (!/[ぁ-んァ-ヴA-Za-z一-鿿]/.test(t)) continue;
    // 「中国（台湾）語」を括弧で分解すると余る「語」単体は分解の副産物。
    // 目視確認すべき件数に混ぜない
    if (t === "語") continue;
    if (!unrecognized.includes(t)) unrecognized.push(t);
  }
  return { languages, unrecognized, negated };
}

/**
 * 既に配列で持っている言語（管理画面での手入力など）を正規化する。
 * 判別できない値は落とさずそのまま残す——運用者が意図して入れた値を消さない。
 */
export function normalizeLanguageList(values: readonly string[] | null | undefined): string[] {
  const out: string[] = [];
  for (const v of values ?? []) {
    const t = String(v ?? "").trim();
    if (!t) continue;
    const n = normalizeLanguageName(t) ?? t;
    if (!out.includes(n)) out.push(n);
  }
  return out;
}
