/**
 * SSR用JSON-LDビルダー（AIクローラー・検索エンジン向け構造化データ）
 * prefetch.tsから各ルートのHeadMeta.jsonLdに渡され、生HTMLの<head>に焼き込まれる。
 * 内部メモ等の非公開情報は一切含めないこと。
 */

const ORIGIN = "https://yatoeru.jp";

type Crumb = { name: string; path: string };

/** パンくずリスト（BreadcrumbList） */
export function breadcrumbLd(crumbs: Crumb[]): Record<string, unknown> {
  return {
    "@context": "https://schema.org",
    "@type": "BreadcrumbList",
    itemListElement: crumbs.map((c, i) => ({
      "@type": "ListItem",
      position: i + 1,
      name: c.name,
      item: `${ORIGIN}${encodeURI(c.path)}`,
    })),
  };
}

/** FAQPage */
export function faqLd(
  faqs: ReadonlyArray<{ q: string; a: string }>
): Record<string, unknown> {
  return {
    "@context": "https://schema.org",
    "@type": "FAQPage",
    mainEntity: faqs.map((f) => ({
      "@type": "Question",
      name: f.q,
      acceptedAnswer: { "@type": "Answer", text: f.a },
    })),
  };
}

/** Article（コラム・解説記事） */
export function articleLd(opts: {
  headline: string;
  path: string;
  datePublished: string;
  dateModified?: string;
  description?: string;
}): Record<string, unknown> {
  return {
    "@context": "https://schema.org",
    "@type": "Article",
    headline: opts.headline,
    description: opts.description,
    datePublished: opts.datePublished,
    dateModified: opts.dateModified ?? opts.datePublished,
    inLanguage: "ja",
    author: { "@type": "Organization", name: "ヤトエル運営チーム", url: ORIGIN },
    publisher: { "@type": "Organization", name: "ヤトエル", url: ORIGIN },
    mainEntityOfPage: `${ORIGIN}${opts.path}`,
  };
}

