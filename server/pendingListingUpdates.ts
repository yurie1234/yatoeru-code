/**
 * 掲載確認メールの回答から用意した「反映待ちの下書き」。
 *
 * 管理画面（/admin →「掲載確認の反映」タブ）に一覧表示され、
 * 読み込む → 内容を確認 → 「本番に反映する」で admin.updateOrgListing が走る。
 * 反映前に必ず人が目視できるようにしてあり、ここに書いただけでは本番は変わらない。
 *
 * ファイル（＝git）に置くのは、
 *  - 何をどの出典で書いたかの履歴が残る
 *  - 返信メールで約束した内容と実際の反映内容を後から突き合わせられる
 * ため。反映が済んだ項目は、このファイルから削除してコミットする。
 *
 * 実行時にディスクを読まない（esbuildのバンドルに含まれる）ので、
 * デプロイ構成に依存しない。
 */

